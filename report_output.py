heading("Observations")
bullet("**Code-level guardrails are necessary, not optional.** The 7B model followed the "
       "“always look up” rule in Steps 3–4 but broke it in Step 5. A prompt "
       "alone would have let a guessed address through. The tool-boundary check caught it "
       "and turned the mistake into a question for the user.")
bullet("**Practical issues found while building the agent:** (i) Ollama sometimes "
       "dropped a tool call when the model put a long email body into the arguments and "
       "the JSON broke. Resending is therefore a separate resend_email(email_id) tool that "
       "copies the stored text instead of regenerating it. (ii) The model occasionally "
       "returned an empty reply after a tool result, so the orchestrator now sends a "
       "“continue” prompt. (iii) The model sometimes repeated “Subject:” "
       "inside the body, which a sanitiser removes. (iv) The extraction prompt once copied "
       "an example address, so examples with addresses were removed from it.")
bullet("**Small-model limitations remain cosmetic:** some chat replies carry over earlier "
       "text or add a signature (Step 5), and the extractor can over-list recipients "
       "(Step 4). Neither affects what is sent, because only the guarded tools can send "
       "and every email is shown in full first.")
bullet("**Latency:** 36–70 s per instruction (3–5 LLM calls) for a 7B model "
       "decoding at about 11 tokens/s on an 8 GB M1. That is acceptable for an assistant "
       "that waits for human confirmation anyway. A larger hosted model would be faster "
       "and need fewer orchestration fixes.")

